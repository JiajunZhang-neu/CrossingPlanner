_PHENOTYPE_SORTED = tuple(sorted(PHENOTYPE_EN.items(), key=lambda item: len(item[0]), reverse=True))

_NOTE_MALE = re.compile(r"^雄蝇各染色体不重组。$")
_NOTE_LOCK = re.compile(r"^雌性亲本里，带全臂平衡子的染色体对按完全连锁计算。$")
_NOTE_PROXIMAL = re.compile(r"^MRS / MKRS 只抑制 3 号染色体近端交换，其余位点仍按设定的 RF 计算。$")
_NOTE_PLACE = re.compile(r"^(.+) 通常在 (.+) 染色体上，这里写在第 (\d+) 对。$")
_NOTE_CONFUSABLE = re.compile(r"^(.+)：(.+) 与 (.+) 容易看混，这两类只差这一项。$")


def get_language() -> str:
    return _LANG


def set_language(lang: str) -> None:
    global _LANG
    _LANG = "en" if lang == "en" else "zh"


def tr(key: str, **kwargs: object) -> str:
    text = STRINGS.get(_LANG, STRINGS["zh"]).get(key)
    if text is None:
        text = STRINGS["zh"].get(key, key)
    if not kwargs:
        return text
    return text.format(**kwargs)


def localize(text: str) -> str:
    """Translate phenotype phrases. Genotype symbols are left as written."""
    if _LANG == "zh" or not text:
        return text
    for zh, en in _PHENOTYPE_SORTED:
        if zh in text:
            text = text.replace(zh, en)
    return text


def translate_note(note: str) -> str:
    """Turn a stored Chinese warning into the active language."""
    if _LANG == "zh":
        return note
    if _NOTE_MALE.match(note):
        return tr("note_no_male_recomb")
    if _NOTE_LOCK.match(note):
        return tr("note_balancer_lock")
    if _NOTE_PROXIMAL.match(note):
        return tr("note_proximal")
    placed = _NOTE_PLACE.match(note)
    if placed:
        symbol, chrom, number = placed.groups()
        return tr("note_balancer_place", symbol=symbol, chrom=chrom, n=number)
    confused = _NOTE_CONFUSABLE.match(note)
    if confused:
        axis, left, right = confused.groups()
        return tr("note_confusable", axis=localize(axis), a=localize(left), b=localize(right))
    return localize(note)
